import fs from 'node:fs/promises';
import path from 'path';

import { PATH } from '@/other/constants';
import resourcesConfig from '@/source/resources.json';

import type { TImage } from '@/types/resources';

export type TImageMeta = Omit<TImage, 'src'>;

/** Builds the replacement for a markdown image pointing at the resources repo. */
export type TImageRenderer = (
  alt: string,
  src: string,
  meta: TImageMeta | undefined
) => string;

const escapeRegExp = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

// "git+https://github.com/<owner>/<repo>.git#<ref>" -> "https://github.com/<owner>/<repo>"
const RESOURCES_REPO_URL = resourcesConfig.resources
  .replace(/^git\+/, '')
  .replace(/#.*$/, '')
  .replace(/\.git$/, '');
const RESOURCES_RAW_URL = RESOURCES_REPO_URL.replace(
  'https://github.com/',
  'https://raw.githubusercontent.com/'
);

// `<repo>/(blob|raw)/<branch>/images/<path>?raw=true` or the
// raw.githubusercontent.com equivalent; branch may contain slashes
// (e.g. `feature/x`, `refs/heads/x`). Captures the path under images/.
const RESOURCE_URL_PART = `(?:${escapeRegExp(RESOURCES_REPO_URL)}/(?:blob|raw)|${escapeRegExp(RESOURCES_RAW_URL)})/[^)\\s]+?/images/([^)?\\s]+)(?:\\?[^)\\s]*)?`;

const RESOURCE_MD_IMAGE_RE = new RegExp(
  `!\\[([^\\]]*)\\]\\(${RESOURCE_URL_PART}\\)`,
  'g'
);
const RESOURCE_LINK_RE = new RegExp(`\\]\\(${RESOURCE_URL_PART}\\)`, 'g');

const IMG_PUBLIC_PREFIX = '/images/resources/';

let imagesMetaCache: Record<string, TImageMeta> | null = null;

/**
 * Standalone image meta generated by install:post-fetch from the resources
 * package's top-level `images` array (source/books/images.json).
 */
export async function getImagesMeta(): Promise<Record<string, TImageMeta>> {
  if (!imagesMetaCache) {
    try {
      const p = path.join(process.cwd(), PATH.DIR.SOURCE_BOOKS, 'images.json');
      imagesMetaCache = JSON.parse(await fs.readFile(p, 'utf8'));
    } catch {
      imagesMetaCache = {};
    }
  }
  return imagesMetaCache;
}

/**
 * Rewrites markdown image/links pointing at the shared resources repo (the git
 * URL in source/resources.json) to the local copy that install:post-fetch
 * places in public/images/resources — served from our origin, loads faster
 * than GitHub. Images go through `renderImage`, which decides the output
 * format for the content type's renderer.
 */
export function localizeResourceImages(
  text: string,
  images: Record<string, TImageMeta>,
  renderImage: TImageRenderer
): string {
  return text
    .replace(RESOURCE_MD_IMAGE_RE, (_match, alt: string, rel: string) =>
      renderImage(alt, IMG_PUBLIC_PREFIX + rel, images[rel])
    )
    .replace(RESOURCE_LINK_RE, `](${IMG_PUBLIC_PREFIX}$1)`);
}
