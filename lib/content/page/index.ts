import fs from 'node:fs/promises';
import path from 'path';

import { getPageBySlug } from '@/lib/page';
import { getIndexesByBookId } from '@/lib/contents';
import { getPageMeta } from '@/lib/content/page/meta';
import { renderPage } from '@/lib/content/page/export';
import { linkifySongRefs } from '@/lib/content/page/songRefs';
import { ITEM_TYPE } from '@/types/common';
import { PATH } from '@/other/constants';
import resourcesConfig from '@/source/resources.json';

import type { ContentHandler } from '@/lib/content/handler';
import type { TImage } from '@/types/resources';
import type { TPage } from '@/types/page';

type TImageMeta = Omit<TImage, 'src'>;

const escapeRegExp = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

// "git+https://github.com/<owner>/<repo>.git" -> "https://github.com/<owner>/<repo>"
const RESOURCES_REPO_URL = resourcesConfig.resources
  .replace(/^git\+/, '')
  .replace(/\.git$/, '');
const RESOURCES_RAW_URL = RESOURCES_REPO_URL.replace(
  'https://github.com/',
  'https://raw.githubusercontent.com/'
);

// `<repo>/blob/<branch>/images/<path>?raw=true` or the
// raw.githubusercontent.com equivalent; captures the path under images/.
const RESOURCE_URL_PART = `(?:${escapeRegExp(RESOURCES_REPO_URL)}/blob|${escapeRegExp(RESOURCES_RAW_URL)})/[^/)]+/images/([^)?\\s]+)(?:\\?[^)\\s]*)?`;

const RESOURCE_MD_IMAGE_RE = new RegExp(
  `!\\[([^\\]]*)\\]\\(${RESOURCE_URL_PART}\\)`,
  'g'
);
const RESOURCE_LINK_RE = new RegExp(`\\]\\(${RESOURCE_URL_PART}\\)`, 'g');

const IMG_PUBLIC_PREFIX = '/images/resources/';

let imagesMetaCache: Record<string, TImageMeta> | null = null;

/**
 * Standalone (page) image meta generated by install:post-fetch from the
 * resources package's top-level `images` array (source/books/images.json).
 */
async function getImagesMeta(): Promise<Record<string, TImageMeta>> {
  if (!imagesMetaCache) {
    try {
      const p = path.join(process.cwd(), PATH.DIR.SOURCE_BOOKS, 'images.json');
      imagesMetaCache = JSON.parse(await fs.readFile(p, 'utf8'));
    } catch {
      imagesMetaCache = {};
    }
  }
  return imagesMetaCache;
}

/**
 * Rewrites image links pointing at the shared resources repo (the git URL in
 * source/resources.json) to the local copy that install:post-fetch places in
 * public/images/resources — served from our origin, loads faster than GitHub.
 * Markdown images with known meta become raw <img> tags (marked passes them
 * through) so the intrinsic width/height prevents layout shift.
 */
function localizeResourceImages(
  body: string,
  images: Record<string, TImageMeta>
): string {
  return body
    .replace(RESOURCE_MD_IMAGE_RE, (match, alt: string, rel: string) => {
      const src = IMG_PUBLIC_PREFIX + rel;
      const meta = images[rel];
      if (!meta) return `![${alt}](${src})`;
      return `<img src="${src}" alt="${alt}" width="${meta.width}" height="${meta.height}">`;
    })
    .replace(RESOURCE_LINK_RE, `](${IMG_PUBLIC_PREFIX}$1)`);
}

/**
 * Rewrites authored relative links between source files, e.g.
 * `(./335-bengali.md)`, `(../songs/x.md)`, `(songs/x.md)` ->
 * `(/<bookId>/<slug>/)`. Slug = filename; the songs/pages dir is irrelevant.
 */
function linkifyRelativeLinks(body: string, bookId: string): string {
  return body.replace(
    /\]\((?:\.{1,2}\/)?(?:(?:songs|pages)\/)?([\w-]+)\.md\)/g,
    `](/${bookId}/$1/)`
  );
}

/**
 * Loads a page and linkifies indented "first line + page number" song
 * references and relative page links, so the app view and the export
 * share the same body.
 */
async function loadPage(slug: string, bookId: string): Promise<TPage | null> {
  const page = await getPageBySlug(slug, bookId);
  if (!page) return null;

  const indexes = await getIndexesByBookId(bookId);
  const localized = localizeResourceImages(page.body, await getImagesMeta());
  const body = linkifyRelativeLinks(localized, bookId);
  return { ...page, body: linkifySongRefs(body, indexes, bookId) };
}

/**/
export const pageHandler: ContentHandler<TPage> = {
  type: ITEM_TYPE.PAGE,
  indexEntryClass: 'page',
  load: loadPage,
  getMeta: getPageMeta,
  renderExport: renderPage
};
